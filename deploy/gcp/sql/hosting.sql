-- BEGIN RATE LIMIT
CREATE SCHEMA IF NOT EXISTS nexoruta_hosting AUTHORIZATION nexoruta_hosting_owner;
REVOKE ALL ON SCHEMA nexoruta_hosting FROM PUBLIC;
CREATE TABLE IF NOT EXISTS nexoruta_hosting.rate_limits (
    "key" text NOT NULL CHECK ("key" ~ '^[0-9a-f]{64}$'),
    "window" bigint NOT NULL,
    "count" integer NOT NULL CHECK ("count" BETWEEN 1 AND 1001),
    PRIMARY KEY ("key", "window")
);
ALTER TABLE nexoruta_hosting.rate_limits OWNER TO nexoruta_hosting_owner;
CREATE INDEX IF NOT EXISTS rate_limits_expiry ON nexoruta_hosting.rate_limits ("window");
REVOKE ALL ON nexoruta_hosting.rate_limits FROM PUBLIC;

CREATE OR REPLACE FUNCTION nexoruta_hosting.take_rate_limit(p_key text, p_limit integer)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, nexoruta_hosting
AS $take_rate_limit$
DECLARE current_window bigint := floor(extract(epoch FROM clock_timestamp()) / 60)::bigint;
        attempts integer;
BEGIN
    IF p_key IS NULL OR p_key !~ '^[0-9a-f]{64}$' OR p_limit IS NULL OR p_limit NOT BETWEEN 1 AND 1000 THEN
        RAISE EXCEPTION 'Invalid rate-limit parameters.' USING ERRCODE = '22023';
    END IF;
    INSERT INTO nexoruta_hosting.rate_limits AS counter ("key", "window", "count")
        VALUES (p_key, current_window, 1)
        ON CONFLICT ("key", "window") DO UPDATE
        SET "count" = LEAST(counter."count" + 1, 1001)
        RETURNING "count" INTO attempts;
    DELETE FROM nexoruta_hosting.rate_limits WHERE ctid IN (
        SELECT ctid FROM nexoruta_hosting.rate_limits
        WHERE "window" < current_window - 2 ORDER BY "window" LIMIT 100 FOR UPDATE SKIP LOCKED
    );
    RETURN attempts <= p_limit;
END
$take_rate_limit$;
ALTER FUNCTION nexoruta_hosting.take_rate_limit(text, integer) OWNER TO nexoruta_hosting_owner;
REVOKE ALL ON FUNCTION nexoruta_hosting.take_rate_limit(text, integer) FROM PUBLIC;
GRANT USAGE ON SCHEMA nexoruta_hosting TO nexoruta_api_runtime;
GRANT EXECUTE ON FUNCTION nexoruta_hosting.take_rate_limit(text, integer) TO nexoruta_api_runtime;
