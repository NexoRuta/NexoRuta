-- CREATEROLE gives the creator ADMIN on newly created roles. PostgreSQL 18
-- rejects granting ADMIN back to yourself; enable ownership operations without
-- granting membership to any runtime login. Existing roles must be administrable
-- by this provisioning login, otherwise fail closed for administrator repair.
SELECT format('GRANT %I TO %I WITH INHERIT TRUE, SET TRUE', role_name, current_user)
FROM (VALUES ('nexoruta_hosting_owner'), ('nexoruta_monitor_fn'),
    ('nexoruta_keys_api'), ('nexoruta_keys_admin'), ('nexoruta_keys_backoffice'),
    ('nexoruta_keys_commerce'), ('nexoruta_keys_tracking'),
    ('nexoruta_grafana_runtime')) roles(role_name)
\gexec

DO $technical_roles$
DECLARE membership record; key_role text;
BEGIN
    FOR membership IN
        SELECT member_role.rolname AS member_name, granted_role.rolname AS granted_name
        FROM pg_auth_members m
        JOIN pg_roles member_role ON member_role.oid = m.member
        JOIN pg_roles granted_role ON granted_role.oid = m.roleid
        WHERE member_role.rolname IN ('nexoruta_keys_api', 'nexoruta_keys_admin', 'nexoruta_keys_backoffice',
            'nexoruta_keys_commerce', 'nexoruta_keys_tracking', 'nexoruta_monitor_runtime',
            'nexoruta_grafana_runtime', 'nexoruta_hosting_owner', 'nexoruta_monitor_fn')
    LOOP
        EXECUTE format('REVOKE %I FROM %I', membership.granted_name, membership.member_name);
    END LOOP;

    FOREACH key_role IN ARRAY ARRAY['nexoruta_keys_api', 'nexoruta_keys_admin', 'nexoruta_keys_backoffice',
        'nexoruta_keys_commerce', 'nexoruta_keys_tracking']
    LOOP
        EXECUTE format('CREATE SCHEMA IF NOT EXISTS %I AUTHORIZATION %I', key_role, key_role);
        EXECUTE format('ALTER SCHEMA %I OWNER TO %I', key_role, key_role);
        EXECUTE format('REVOKE ALL ON SCHEMA %I FROM PUBLIC', key_role);
        EXECUTE format('CREATE TABLE IF NOT EXISTS %I."DataProtectionKeys" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "FriendlyName" text NULL, "Xml" text NULL)', key_role);
        EXECUTE format('ALTER TABLE %I."DataProtectionKeys" OWNER TO %I', key_role, key_role);
        EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA %I FROM PUBLIC', key_role);
        EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA %I FROM PUBLIC', key_role);
        EXECUTE format('GRANT SELECT, INSERT, UPDATE ON %I."DataProtectionKeys" TO %I', key_role, key_role);
        EXECUTE format('GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA %I TO %I', key_role, key_role);
    END LOOP;
END
$technical_roles$;

