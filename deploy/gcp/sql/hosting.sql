CREATE OR REPLACE FUNCTION nexoruta_hosting.outbox_metrics()
RETURNS TABLE (transport text, state text, messages bigint, oldest_age_seconds double precision)
LANGUAGE sql SECURITY DEFINER SET search_path = pg_catalog, nexoruta_hosting
AS $outbox_metrics$
    SELECT "Destino"::text, "Estado"::text, count(*),
        CASE WHEN "Estado" = 'Publicado' THEN 0::double precision
             ELSE greatest(0, extract(epoch FROM clock_timestamp() - min("CreadoEnUtc")))::double precision END
    FROM public."OutboxMessages" GROUP BY "Destino", "Estado"
$outbox_metrics$;
ALTER FUNCTION nexoruta_hosting.outbox_metrics() OWNER TO nexoruta_monitor_fn;
