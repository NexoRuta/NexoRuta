const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'../..');
const artifacts=path.join(root,'.local/codex-cloud/cu08-browser');fs.mkdirSync(artifacts,{recursive:true});
const {chromium}=require(path.join(__dirname,'node_modules/playwright'));
(async()=>{
const s=JSON.parse(fs.readFileSync(path.join(root,'.local/codex-cloud/private.json'),'utf8'));
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
await page.route(/https?:\/\/(?!127\.0\.0\.1|localhost)/,route=>route.abort());
await page.goto('http://127.0.0.1:5102/ingresar');
await page.locator('#Email').fill(s.commerceEmail);await page.locator('#Password').fill(s.commercePassword);
await page.getByRole('button',{name:/Ingresar/}).click();
await page.waitForURL(u=>!u.pathname.includes('ingresar'));
await page.goto('http://127.0.0.1:5102/envios/crear');
await page.getByRole('button',{name:'Agregar bulto'}).waitFor();
await page.getByRole('combobox',{name:'Operador',exact:true}).selectOption(s.operatorId);
await page.getByRole('button',{name:'Agregar bulto'}).click();
await page.getByRole('group',{name:'Bulto 2',exact:true}).waitFor();
await page.screenshot({path:path.join(artifacts,'desktop.png'),fullPage:true});
await page.setViewportSize({width:320,height:900});
await page.screenshot({path:path.join(artifacts,'320.png'),fullPage:true});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
if(overflow)throw Error('Page overflows at 320px');
await page.getByRole('button',{name:'Quitar bulto 2'}).click();
if(await page.getByRole('group',{name:'Bulto 2',exact:true}).count())throw Error('Remove failed');
console.log('Chromium desktop/320: add/remove parcels; no horizontal overflow. External requests blocked.');
await browser.close();
})().catch(e=>{console.error(e.message);process.exit(1)});
